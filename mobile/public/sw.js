/* FitTrack Pro — service worker.
 *
 * Two jobs: make the app open without a network, and satisfy Chrome's
 * installability criteria so it can be added to a home screen as a real app
 * rather than a browser shortcut.
 *
 * The one rule that matters most here is what this file does NOT cache.
 * Everything under /api is authenticated, per-user and time-sensitive: the
 * whole point of the app is that every number on screen is computed from what
 * the signed-in user actually logged. Serving a cached copy would show stale
 * macros as if they were current, and would leave one account's data sitting
 * in Cache Storage where the next person to open the browser on a shared phone
 * could read it. API requests are therefore passed straight through to the
 * network, untouched — this worker never even inspects their responses.
 *
 * Written by hand rather than generated by Workbox to match the rest of this
 * codebase, which has no UI or utility libraries either. The precache list is
 * the only generated part: mobile/build/precache-plugin.js rewrites the two
 * placeholders below at build time, because Vite's output filenames are
 * content-hashed and cannot be known before the bundle exists.
 */

const VERSION = '__PRECACHE_VERSION__';
const PRECACHE = '__PRECACHE_MANIFEST__';

const CACHE = `fittrack-mobile-${VERSION}`;

/** Font stylesheets and the font files they pull, cached so the brand
 *  typography survives offline instead of falling back to a system stack. */
const FONT_HOSTS = ['https://fonts.googleapis.com', 'https://fonts.gstatic.com'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // addAll is atomic — one 404 aborts the whole install, which is what we
      // want: a half-populated precache is worse than none, because it fails
      // later and at random rather than now and loudly.
      await cache.addAll(PRECACHE);
      // Take over on the next load rather than waiting for every tab to close.
      // The page that is open right now keeps the JS it has already parsed.
      await self.skipWaiting();
    })()
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names
          .filter((name) => name.startsWith('fittrack-mobile-') && name !== CACHE)
          .map((name) => caches.delete(name))
      );
      await self.clients.claim();
    })()
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;

  // Only GET is cacheable, and only http(s) — a POST, or a chrome-extension://
  // request, goes straight to the network.
  if (request.method !== 'GET' || !request.url.startsWith('http')) return;

  const url = new URL(request.url);
  const sameOrigin = url.origin === self.location.origin;

  // Never touch the API. See the note at the top of this file.
  if (sameOrigin && url.pathname.startsWith('/api/')) return;

  // A navigation is answered from the network first so a new deploy is picked
  // up immediately, and falls back to the cached shell when there is none.
  // The SPA router resolves the actual route once the shell boots.
  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        try {
          return await fetch(request);
        } catch {
          const cache = await caches.open(CACHE);
          // Both spellings are precached; which one a given browser stores the
          // shell under depends on how it normalised the request, so try each.
          const shell = (await cache.match('/index.html')) ?? (await cache.match('/'));
          return shell ?? Response.error();
        }
      })()
    );
    return;
  }

  const isFont = FONT_HOSTS.includes(url.origin);
  if (!sameOrigin && !isFont) return;

  // Everything else — hashed JS and CSS, icons, fonts — is immutable at its
  // URL, so cache-first is both correct and the fastest path. A miss is
  // fetched and stored, which is what fills in lazily-loaded route chunks the
  // first time each screen is opened.
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(request);
      if (cached) return cached;

      try {
        const response = await fetch(request);
        // Opaque responses (no-cors cross-origin) report status 0 and cannot
        // be inspected; storing one risks caching an error page forever.
        if (response.ok) cache.put(request, response.clone());
        return response;
      } catch (error) {
        // Offline and not in the cache: let the failure surface rather than
        // inventing a response the app would have to guess the meaning of.
        throw error;
      }
    })()
  );
});
